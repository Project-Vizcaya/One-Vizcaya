#!/usr/bin/env node
// Imports Nueva Vizcaya's DPWH flood-control projects (docs/flood-control.md).
//
// Source: BetterGov.ph's copy of the DPWH Flood Control Information System,
// taken from their v1 repository, which was released under CC0 (public
// domain). Use the file as it was before their 2026-11-19 relicensing:
//
//   git clone https://github.com/bettergovph/bettergov.git
//   git -C bettergov show 1d2e8f3~1:src/data/flood_control/flood_control.json > fc.json
//   node scripts/import-dpwh-flood-control.mjs fc.json
//
// Writes the same records for the console and the app:
//   apps/web/src/data/floodControl.ts
//   apps/mobile/assets/data/flood_control.json

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const WEB_OUT = "apps/web/src/data/floodControl.ts";
const APP_OUT = "apps/mobile/assets/data/flood_control.json";

// The app's town names (AppConstants / MunicipalityInfoService).
const TOWNS = [
  "Alfonso Castañeda", "Ambaguio", "Aritao", "Bagabag", "Bambang", "Bayombong", "Diadi",
  "Dupax del Norte", "Dupax del Sur", "Kasibu", "Kayapa", "Quezon", "Santa Fe", "Solano", "Villaverde",
];
const plain = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase();
const BY_PLAIN = new Map(TOWNS.map((t) => [plain(t), t]));

// DPWH: "BAYOMBONG (CAPITAL) (NUEVA VIZCAYA)". When DPWH left the town
// blank, every description so far ends ", <Town>, Nueva Vizcaya".
function townOf(r) {
  if (r.Municipality) {
    const t = BY_PLAIN.get(plain(r.Municipality.replace(/\s*\(.*$/, "").trim()));
    if (!t) throw new Error(`Unknown town "${r.Municipality}" in ${r.ContractID}`);
    return { town: t, townFromDescription: false };
  }
  const m = plain(r.ProjectDescription ?? "").match(/,\s*([^,]+),\s*NUEVA VIZCAYA\s*$/);
  const t = m && BY_PLAIN.get(m[1].trim());
  return { town: t ?? null, townFromDescription: !!t };
}

// "05/02/2023" (MM/DD/YYYY) -> "2023-05-02"
const isoDate = (s) => {
  const m = /^(\d{2})\/(\d{2})\/(\d{4})$/.exec(s ?? "");
  return m ? `${m[3]}-${m[1]}-${m[2]}` : null;
};

const src = process.argv[2];
if (!src) { console.error("Usage: node scripts/import-dpwh-flood-control.mjs <flood_control.json>"); process.exit(1); }
const data = JSON.parse(readFileSync(src, "utf8"));

const projects = data.features
  .map((f) => f.attributes)
  .filter((r) => r.Province === "NUEVA VIZCAYA")
  .map((r) => ({
    id: r.ContractID,
    description: r.ProjectDescription,
    typeOfWork: r.TypeofWork,
    ...townOf(r),
    lat: r.Latitude,
    lng: r.Longitude,
    year: r.InfraYear,
    budget: r.ABC,
    contractCost: r.ContractCost,
    contractor: r.Contractor,
    startDate: isoDate(r.StartDate),
    completedDate: r.CompletionDateActual || null,
    office: r.DistrictEngineeringOffice,
  }))
  .sort((a, b) => (b.year - a.year) || a.id.localeCompare(b.id));

if (projects.length === 0) throw new Error("No Nueva Vizcaya projects in the file.");
if (new Set(projects.map((p) => p.id)).size !== projects.length) throw new Error("Duplicate contract IDs.");

const meta = {
  source: "DPWH Flood Control Information System, via BetterGov.ph (v1, CC0)",
  sourceUrl: "https://github.com/bettergovph/bettergov",
  snapshot: "2025-08",
  count: projects.length,
};

writeFileSync(join(root, WEB_OUT), `// GENERATED by scripts/import-dpwh-flood-control.mjs. Do not edit by hand.
// ${meta.source}. Snapshot ${meta.snapshot}. See docs/flood-control.md.

export interface FloodControlProject {
  id: string;
  description: string;
  typeOfWork: string;
  town: string | null;
  /** DPWH left the town blank; it was read from the description. */
  townFromDescription: boolean;
  lat: number;
  lng: number;
  year: number;
  budget: number;
  contractCost: number;
  contractor: string;
  startDate: string | null;
  completedDate: string | null;
  office: string;
}

export const FLOOD_CONTROL_META = ${JSON.stringify(meta, null, 2)} as const;

export const FLOOD_CONTROL_PROJECTS: FloodControlProject[] = ${JSON.stringify(projects, null, 1)};
`);
mkdirSync(join(root, dirname(APP_OUT)), { recursive: true });
writeFileSync(join(root, APP_OUT), JSON.stringify({ ...meta, projects }, null, 1) + "\n");
console.log(`Wrote ${projects.length} projects to ${WEB_OUT} and ${APP_OUT}.`);
